#!/usr/bin/env python3
"""Write a .env for the four self-hosted targets, with generated passwords.

    python scripts/init_env.py              # self-hosted targets only
    python scripts/init_env.py --managed    # also stub the managed targets

The self-hosted containers need credentials, but nobody needs to *choose*
them: they exist only so the engines are not running unauthenticated, and they
never leave the machine. Generating them removes the one manual step most
likely to be done badly - a weak reused password typed in a hurry - and the
one most likely to be skipped, which leaves the run failing on a missing
variable ten minutes in.

Memgraph and FalkorDB run unauthenticated by default, so their password
variables are deliberately left empty. That is not an oversight; it is what
those images do, and the harness treats an empty username as "no auth" rather
than as an empty credential.

Refuses to overwrite an existing .env. Rotating a password means deleting the
file yourself, which is a decision worth making on purpose because the
containers hold data created under the old one.
"""

from __future__ import annotations

import argparse
import contextlib
import secrets
import stat
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]

SELF_HOSTED = """\
# Generated by scripts/init_env.py. NEVER COMMIT THIS FILE.
# .gitignore excludes it; scripts/scan_secrets.py fails the build if it is
# ever tracked anyway.

# ---- Self-hosted, resource-capped containers -------------------------------
# Started one at a time by scripts/run_suite.sh. These passwords are local to
# this machine and are generated rather than chosen.

NEO4J_URI=bolt://localhost:7687
NEO4J_USERNAME=neo4j
NEO4J_PASSWORD={neo4j}

# Memgraph runs unauthenticated by default. An empty username tells the
# harness to connect with auth=None, which is not the same as sending an
# empty username and password.
MEMGRAPH_URI=bolt://localhost:7688
MEMGRAPH_USERNAME=
MEMGRAPH_PASSWORD=

# FalkorDB likewise starts without a password.
FALKORDB_HOST=localhost
FALKORDB_PORT=6379
FALKORDB_PASSWORD=

ARANGO_URL=http://localhost:8529
ARANGO_USERNAME=root
ARANGO_PASSWORD={arango}

# Container resource caps, applied by infra/docker-compose.yml and verified by
# scripts/probe_limits.py. One vCPU and 2 GB per database, measured one at a
# time, fits the default 2-core / 8 GB Codespace with a core left for the
# benchmark client.
CPU_LIMIT=1
MEMORY_LIMIT=2g
"""

MANAGED = """
# ---- Managed targets (not configured) --------------------------------------
# Left empty on purpose. The harness reports an unconfigured target as
# "not configured" in every table rather than omitting it, so an empty block
# here produces an honest report rather than a silently narrower one.

COGNODB_URI=
COGNODB_USERNAME=cognodb
COGNODB_PASSWORD=
COGNODB_REGION=

AURA_URI=
AURA_USERNAME=neo4j
AURA_PASSWORD=
AURA_REGION=
"""


def generate_password() -> str:
    """A URL-safe token: no quoting problems in .env, compose, or a Bolt URI."""
    return secrets.token_urlsafe(24)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--managed",
        action="store_true",
        help="include empty CognoDB and Aura blocks for filling in later",
    )
    parser.add_argument("--path", type=Path, default=REPO_ROOT / ".env")
    args = parser.parse_args()

    if args.path.exists():
        print(
            f"{args.path} already exists; refusing to overwrite it.\n"
            f"The containers may hold data created under the current password. "
            f"Delete the file yourself if you really mean to rotate.",
            file=sys.stderr,
        )
        return 1

    content = SELF_HOSTED.format(neo4j=generate_password(), arango=generate_password())
    if args.managed:
        content += MANAGED

    args.path.write_text(content, encoding="utf-8")
    # Owner-only. Effectively a no-op on Windows, which is why .gitignore and
    # the secret scanner - not the file mode - are what actually keep this file
    # out of the repository.
    with contextlib.suppress(OSError):
        args.path.chmod(stat.S_IRUSR | stat.S_IWUSR)

    print(f"wrote {args.path} with generated passwords for neo4j and arangodb")
    print("memgraph and falkordb are left unauthenticated, as their images ship")
    print("\nNext: make smoke")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
